subroutine initialize
    use the_whole_varibles
    implicit none
    integer:: I_r,I_z,i1,i2,nmlid
    real*8  r_resonance,z_resonance,b0_set
    real*8  total_cycles,tau_ion_predicted


    !<4namelist>
    namelist /ini/ &
        & mass_number, &
        & frequency, &
        & runHowManyPeriods, &
        & runRFonWhichPeriod, &
        & np_max, &
        & iswitch_dielectric, &
        & iswitch_analytic_temperature, &
        & k_closure_type, &
        & k_constant, &
        & till_uni, &
        & tipp_uni, &
        & tell_uni, &
        & t2pp_uni, &
        & iswitch_analytic_profile, &
        & iswitch_mcc, &
        & iswitch_antenna_type, &
        & irf_set, &
        & resistance, &
        & i_switch_B0, &
        & max_density_set, &
        & vz0, &
        & vl_in_FDFD, &
        & n_pic, &
        & z_inject_cener, &
        & z_resonance, &
        & outputDir, &
        & b0Dir, &
        & kapDir, &
        & plasmaLoadDir, &
        & iswitch_log
    
    namelist /dev/ &
        & dev_Only4CalMag
    

    call start_ftime


    open(newunit=nmlid, file=trim(nmlfile), status="old")
    read(nmlid, nml=ini)
    close(nmlid)

    open(newunit=nmlid, file=trim(nmlfile), status="old")
    read(nmlid, nml=dev)
    close(nmlid)

    call mkdir_if_not_exist

    !np_max = 10000 !@namelist

    mi=mass_number*mp
    mass_q_i_05=0.5*mi/qi
    q_mass_i=qi/mi

    trf=1/frequency
    
    allocate(np(1:np_max))
    allocate(life_and_ek(1:np_max,1:2))
    life_and_ek=0.
    allocate(ir1_iz1_grid(1:np_max,1:2))
    allocate(x(1:np_max,1:3))
    allocate(v(1:np_max,1:3))
    allocate(v_e(1:np_max,1:3))
    allocate(t_np(1:np_max))
    allocate(x_to_grid(1:np_max,1:2))
    np_loss_rec = np_max
    allocate(xv_loss(1:np_loss_rec,1:7))
    xv_loss=0.


    !iswitch_dielectric=3 !@namelist
    !iswitch_analytic_temperature = 1 !@namelist
    !k_closure_type=2 !@namelist
    !k_closure_type =1: 每一点用 find_kfc 闭合 k_parallel
    !               =0: 每一点用常数 k_constant 闭合 k_parallel
    !               =2: 每一点用自定义的 kap 文件闭合 k_parallel
    !k_constant=20.0d0 !@namelist
    

    !till_uni = 3.0 !@namelist
    !tipp_uni = 3.0 !@namelist
    !tell_uni = 3.0 !@namelist
    !t2pp_uni = 3.0 !@namelist
    ! eV

    !iswitch_analytic_profile = 1 !@namelist
    ! 0: nothing happens
    ! 1: analytic profile is set in fun_fdfd.f90

    !-----------------------discharge set-------------------------------!
    iswitch_display=1; !1--the running state display on screen; 0--write into a dat file
    
    !iswitch_mcc=1 !@namelist
    !0-monte carlo collsion off, 1-on  !energy conservation

    !iswitch_dielectric= 1: 冷等离子体，包含离子和电子电流
    !                    2: 冷等离子体，仅保留电子电流
    !                    3: 热等离子体，离子动力学 + 电子冷响应
    !                    4: 热等离子体，离子和电子都采用动力学响应
    !iswitch_dielectric=3 !@namelist

    use_file_defined_density=0 !0-Gaussian profile; 1- read from file

    !iswitch_antenna_type= 0, single loop
    !                    =-1, left helical
    !                    = 1, right helical
    !                    = 2, half loop
    !                    = 3, Nagoya type-III
    !iswitch_antenna_type=1 !@namelist

    !important: this version only tests i_switch_power_mode=0. !!!

    i_switch_power_mode=0;
    !1:set constant total power; 0: set constant current Irf

    !irf_set=500; !@namelist
    !A    use when i_switch_power_mode=0;

    power=1e3;             !W    use when i_switch_power_mode=1;
    !resistance=1 !@namelist
    !ohm, antenna resistance,   use when i_switch_power_mode=1;

    iswitch_RF2=0        !0 - swtich off RF2
    irf2_set=1.1*irf_set;         !A


    !i_switch_B0=1: uniform b0_ci you specificly set;
    !           =2: load B0 from txt files;
    !           =3: B0 field generated by coils (subroutine background_b0)
    !i_switch_B0=2 ; !@namelist
    b0_set=1;             !T. Note: used only when i_switch_B0=1, i.e., i_switch_B0=2 or 3--not use;

    i_switch_MHD_Te=0;    !1-te_in_FDFD evolution by MHD; 0-te_in_FDFD evolution only by MCC; 2-constant te_in_FDFD
    Te_set=6;            !eV. Note: use only when i_switch_MHD_Te=2

    !max_density_set=1e19 !@namelist
    !m-3, maxium initial plasma density

    ti_ini=3;            !eV , initial teamperature of ion
    te_ini=3;            !eV

    !vz0=1d1; !@namelist
    !m/s, Ion orientation speed

    !vl_in_FDFD = 5e4 !@namelist

    !n_pic=6 !@namelist
    !total number of picture to record, i.e. record data at every td/n_pic

    !td=3.e-3; !@namelist indirect
    !s
    td = trf * howManyPeriods
    ! t_power_on=1e-5; !@namelist
    !s
    t_power_on =  trf * runRFonWhichPeriod
