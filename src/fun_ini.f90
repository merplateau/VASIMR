    if(tau_ion_predicted>td)tau_ion_predicted=td !when tau_ion>td, use td
    total_cycles=tau_ion_predicted/trf
    if(dt_trf<1e-10)then
        !set dt (Trf), according to the nature of energy conservation (loss <1%) in the RK4 format
        if(total_cycles<50)then
            dt_trf=5e-2
        elseif(total_cycles<1200)then
            dt_trf=2.5e-2
        elseif(total_cycles<1.5e5)then
            dt_trf=1e-2
        elseif(total_cycles<1.5e6)then
            dt_trf=5e-3
        else
            dt_trf=2.5e-3
        endif
    endif
    
    dt=dt_trf*trf;
    
    vi_ex=sqrt(qe_abs*ti_ini/mi);     !expectation of vi :  average speed
    ve_ex=sqrt(qe_abs*te_ini/me);     !expectation of ve :  average speed
    ek_ion_2D=ti_ini*1.5
    ek_ion_2D_r=ek_ion_2D/1.5
    t_rec_profiles=td/real(n_pic)


    call rec_para
    open (unit=42,file=trim(outputDir)//trim('1time_average.dat'),status='unknown',iostat=ierror)
    open (unit=43,file=trim(outputDir)//trim('1time_trajectory.dat'),status='unknown',iostat=ierror)

    if (iswitch_analytic_profile == 1) then
        call readProfileFromFile
    end if

    if (dev_Only4CalMag==1) then
        stop 'Only for calculating magnetic field, stop after background_b0'
    end if
    call readKapFromFile
end subroutine initialize

